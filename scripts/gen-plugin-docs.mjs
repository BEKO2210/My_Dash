// Generates docs/PLUGINS.md from the widget manifest (src/plugins/registry.ts)
// and the English i18n catalogue (src/lib/i18n.tsx). Run with `npm run docs:plugins`.
// The registry uses a one-object-per-line format, so a tolerant line parser keeps
// this dependency-free (no TS runtime needed).

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const registry = readFileSync(join(root, "src/plugins/registry.ts"), "utf8");
const i18n = readFileSync(join(root, "src/lib/i18n.tsx"), "utf8");

// English description lookup: parse "key": "value" pairs from the EN block.
const en = {};
const enStart = i18n.indexOf("const EN");
const enSrc = enStart >= 0 ? i18n.slice(enStart) : i18n;
for (const m of enSrc.matchAll(/"([\w.]+)":\s*"((?:[^"\\]|\\.)*)"/g)) {
  if (!(m[1] in en)) en[m[1]] = m[2];
}

const CATEGORY = {
  overview: "Overview",
  sessions: "Sessions",
  economy: "Economy",
  activity: "Activity",
  tools: "Tools",
  quality: "Quality",
};

const field = (line, key) => {
  const m = line.match(new RegExp(`${key}:\\s*"([^"]+)"`));
  return m ? m[1] : "";
};

const widgets = [];
for (const line of registry.split("\n")) {
  const idMatch = line.match(/^\s*\{\s*id:\s*"([^"]+)"/);
  if (!idMatch) continue;
  const span = field(line, "span");
  const cols = (span.match(/col-span-(\d)/) || [])[1];
  widgets.push({
    id: idMatch[1],
    title: field(line, "title"),
    category: field(line, "category"),
    description: field(line, "description"),
    width: cols ? `${cols}/6` : "—",
    height: field(line, "height") === "h-auto" ? "auto" : "standard",
    settings: /settings:\s*\[/.test(line) ? "yes" : "—",
  });
}

const byCat = {};
for (const w of widgets) (byCat[w.category] ??= []).push(w);

let md = `<!-- AUTO-GENERATED by scripts/gen-plugin-docs.mjs — run \`npm run docs:plugins\` to refresh. -->

# Widget plugins

This catalogue is generated from the widget manifest in \`src/plugins/registry.ts\`.
There are **${widgets.length}** built-in widgets. Third-party widgets dropped into
\`plugins.local/\` are auto-discovered at build (see
[\`plugins.local/README.md\`](../plugins.local/README.md)).

## Authoring a widget

A widget is a manifest object plus a React component:

\`\`\`tsx
import { Sparkles } from "lucide-react";
import type { Widget } from "@/plugins/registry";
import { usePluginQuery } from "@/components/plugin-data"; // typed, read-only data API

function MyWidget() {
  const { data, loading } = usePluginQuery<MyShape>("/api/my-route");
  return <div className="p-4 text-sm text-foreground">…</div>;
}

export const plugin: Widget = {
  id: "my-widget",            // globally unique
  title: "My Widget",
  span: "lg:col-span-3",       // 1–6 columns (default size)
  height: "h-[360px] min-[2560px]:h-[480px] min-[3840px]:h-[660px]",
  icon: Sparkles,
  category: "tools",           // ${Object.keys(CATEGORY).join(" | ")}
  description: "my.descKey",   // i18n key (or literal text)
  // settings: [{ key: "limit", type: "number", label: "…", default: 50 }],
  component: MyWidget,
};
\`\`\`

**Rules:** read-only (GET the dashboard's \`/api/*\` only — never write), unique
\`id\`, isolated by a per-widget error boundary, and configurable via the optional
\`settings\` schema (rendered by the settings drawer, persisted to \`plugin_config\`).

## Built-in widgets

`;

for (const cat of Object.keys(CATEGORY)) {
  const group = byCat[cat];
  if (!group || group.length === 0) continue;
  md += `### ${CATEGORY[cat]}\n\n`;
  md += `| Widget | id | Width | Height | Settings | Description |\n`;
  md += `|---|---|---|---|---|---|\n`;
  for (const w of group) {
    const desc = en[w.description] ?? w.description;
    md += `| ${w.title} | \`${w.id}\` | ${w.width} | ${w.height} | ${w.settings} | ${desc} |\n`;
  }
  md += `\n`;
}

writeFileSync(join(root, "docs", "PLUGINS.md"), md);
console.log(`gen-plugin-docs: wrote docs/PLUGINS.md (${widgets.length} widgets)`);
